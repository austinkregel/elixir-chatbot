defmodule Brain.ML.KnowledgeGraph.TripleScorer do
  @moduledoc """
  Scores knowledge graph triples (head, relation, tail) for validity using
  a BiLSTM encoder.

  Architecture:
      Input: "[HEAD] entity_name [REL] relation_type [TAIL] entity_name"
        -> Tokenize -> Embedding -> BiLSTM
        -> Masked mean pool -> Dense(128) -> ReLU -> Dropout -> Dense(1) -> Sigmoid
        -> Binary cross-entropy loss

  Trained with negative sampling: positive triples from the knowledge graph,
  negatives generated by corrupting head or tail entities. `mix train_kg_lstm`
  writes the trained scorer to `trained_path/0`.

  The scorer judges triples over a world's nomens, so it belongs to a world. A
  world holds its own copy at `<world>/models/triple_scorer.term` (`path/1`),
  seeded by copying the trained scorer:

  - a persistent world is seeded when `World.Manager` creates it, and an existing
    world, or every world after a retrain, with `mix world.seed_model triple_scorer`;
  - an ephemeral world has no directory, so it is seeded in memory when it is
    created (`seed_in_memory!/1`) and dropped with it (`drop/1`).

  `loaded!/1` reads a world's copy the first time the world scores and keeps it
  in `:persistent_term`. Every score names its world. A world with no copy raises
  naming the world: there is no fallback to the trained scorer or to another
  world. Seeding or dropping a world's copy forgets the entity vectors
  `Brain.ML.KnowledgeGraph.EntityVectorCache` computed from the copy it replaces.
  """

  require Logger

  alias Brain.ML.KnowledgeGraph.EntityVectorCache
  alias Brain.ML.{Tokenizer, TrainingSeed, WorldModelFile}

  @default_embedding_dim 64
  @default_hidden_dim 128
  @default_max_seq_length 32
  @default_epochs 50
  @default_learning_rate 0.001
  @special_tokens ["[HEAD]", "[REL]", "[TAIL]", "[PAD]"]

  @file_name "triple_scorer.term"

  # --- Scoring in a world ---

  @doc """
  Score a triple for validity with the world's scorer.

  Returns `{:ok, score}` where score is in (0, 1). Higher scores indicate more
  likely valid triples. Raises when the world has no copy of the scorer.
  """
  @spec score(String.t(), String.t(), String.t(), String.t()) :: {:ok, float()}
  def score(world_id, head, relation, tail) when is_binary(world_id) do
    do_score(head, relation, tail, loaded!(world_id))
  end

  @doc """
  Score multiple `{head, relation, tail}` triples with the world's scorer.

  Returns `{:ok, [score]}`. Raises when the world has no copy of the scorer.
  """
  @spec score_batch(String.t(), [{String.t(), String.t(), String.t()}]) :: {:ok, [float()]}
  def score_batch(world_id, triples) when is_binary(world_id) and is_list(triples) do
    scorer = loaded!(world_id)

    scores =
      Enum.map(triples, fn {h, r, t} ->
        {:ok, s} = do_score(h, r, t, scorer)
        s
      end)

    {:ok, scores}
  end

  @doc """
  The world's relation coverage, `%{relation => positive_count}`: how many
  positive triples of each relation its scorer was trained on.

  Used by `PredicateNormalizer` to decide whether a lemma-passthrough
  predicate was part of the training vocabulary.
  """
  @spec relation_coverage(String.t()) :: %{String.t() => non_neg_integer()}
  def relation_coverage(world_id) when is_binary(world_id), do: loaded!(world_id).relation_coverage

  @doc "The model version recorded in the world's copy of the scorer, or nil when it records none."
  @spec current_model_version(String.t()) :: String.t() | nil
  def current_model_version(world_id) when is_binary(world_id), do: loaded!(world_id).model_version

  # --- A world's copy ---

  @doc "Where a world keeps its copy of the triple scorer."
  @spec path(String.t()) :: Path.t()
  def path(world_id) when is_binary(world_id), do: WorldModelFile.path(world_id, @file_name)

  @doc "Where training writes the triple scorer that worlds are seeded from."
  @spec trained_path() :: Path.t()
  def trained_path, do: WorldModelFile.trained_path(@file_name)

  @doc """
  Whether the world holds a copy of the scorer: loaded, or on disk to be read
  the first time it scores. For reporting a world's state; scoring in a world
  without a copy raises.
  """
  @spec held?(String.t()) :: boolean()
  def held?(world_id) when is_binary(world_id) do
    :persistent_term.get(key(world_id), nil) != nil or File.regular?(path(world_id))
  end

  @doc """
  The world's scorer, read from its copy the first time it is asked for: the
  Axon model with its parameters, vocabulary, config, relation coverage and
  model version.
  """
  @spec loaded!(String.t()) :: map()
  def loaded!(world_id) when is_binary(world_id) do
    case :persistent_term.get(key(world_id), nil) do
      nil ->
        scorer = world_id |> path() |> read!(world_id) |> build_scorer()
        :persistent_term.put(key(world_id), scorer)
        scorer

      scorer ->
        scorer
    end
  end

  @doc """
  Copies the trained scorer into the world's models directory, checks the copy
  byte for byte, and makes it the world's loaded scorer. Replaces any copy the
  world held, which is how a retrained scorer reaches a world.
  """
  @spec seed!(String.t()) :: :ok
  def seed!(world_id) when is_binary(world_id) do
    scorer = trained_path() |> read!(:trained) |> build_scorer()
    :ok = WorldModelFile.copy!(world_id, @file_name)
    :persistent_term.put(key(world_id), scorer)
    EntityVectorCache.forget_world(world_id)
  end

  @doc "Makes a copy of the trained scorer the loaded scorer of a world that has no directory."
  @spec seed_in_memory!(String.t()) :: :ok
  def seed_in_memory!(world_id) when is_binary(world_id) do
    :persistent_term.put(key(world_id), trained_path() |> read!(:trained) |> build_scorer())
    EntityVectorCache.forget_world(world_id)
  end

  @doc "Forgets the world's loaded scorer, for a world that is destroyed."
  @spec drop(String.t()) :: :ok
  def drop(world_id) when is_binary(world_id) do
    :persistent_term.erase(key(world_id))
    EntityVectorCache.forget_world(world_id)
  end

  @doc """
  Reads and checks a triple scorer file. Raises when it is missing, or does not
  hold parameters with a vocabulary of the size its config records.
  """
  @spec read!(Path.t(), String.t() | :trained) :: map()
  def read!(file, owner) do
    unless File.regular?(file) do
      raise missing_message(file, owner)
    end

    case file |> File.read!() |> :erlang.binary_to_term() do
      %{params: params, vocab: vocab, config: %{vocab_size: vocab_size} = config} = data
      when is_map(vocab) and map_size(vocab) > 0 ->
        unless vocab_size == map_size(vocab) do
          raise "TripleScorer: #{file} config says vocab_size #{vocab_size} but its vocab has #{map_size(vocab)} entries"
        end

        %{data | params: ensure_model_state(params), config: config}

      other ->
        raise "TripleScorer: #{file} does not hold a triple scorer, got #{inspect(other, limit: 3)}"
    end
  end

  defp build_scorer(data) do
    %{
      model:
        build_model(data.config.vocab_size,
          embedding_dim: data.config.embedding_dim,
          hidden_dim: data.config.hidden_dim
        ),
      params: data.params,
      vocab: data.vocab,
      config: data.config,
      relation_coverage: Map.get(data, :relation_coverage, %{}),
      model_version: Map.get(data, :model_version)
    }
  end

  defp missing_message(file, :trained),
    do: "TripleScorer: no trained triple scorer at #{file}; train one with `mix train_kg_lstm`"

  defp missing_message(file, world_id),
    do:
      "TripleScorer: world #{inspect(world_id)} has no triple scorer at #{file}; " <>
        "seed it with `mix world.seed_model triple_scorer --world #{world_id}`"

  defp key(world_id), do: {__MODULE__, world_id}

  # --- Training ---

  @doc """
  Build the triple scoring Axon model.

  ## Parameters
    - `vocab_size` - Size of token vocabulary
    - `opts` - Options:
      - `:embedding_dim` - Embedding dimension (default: #{@default_embedding_dim})
      - `:hidden_dim` - LSTM hidden dimension (default: #{@default_hidden_dim})
      - `:max_seq_length` - Maximum sequence length (default: #{@default_max_seq_length})
      - `:seed` - Seed for the LSTM's initial-state key and dropout's key
        (default: `Brain.ML.TrainingSeed.get!/0`). Axon otherwise seeds both
        from the clock. A loaded model restores these keys from its saved
        parameters, so the seed only affects training.
  """
  def build_model(vocab_size, opts \\ []) do
    embedding_dim = Keyword.get(opts, :embedding_dim, @default_embedding_dim)
    hidden_dim = Keyword.get(opts, :hidden_dim, @default_hidden_dim)
    max_seq_length = Keyword.get(opts, :max_seq_length, @default_max_seq_length)
    seed = Keyword.get_lazy(opts, :seed, &TrainingSeed.get!/0)

    input = Axon.input("input", shape: {nil, max_seq_length})
    mask_input = Axon.input("mask", shape: {nil, max_seq_length, 1})

    encoder =
      input
      |> Axon.embedding(vocab_size, embedding_dim, name: "embedding")
      |> Axon.lstm(hidden_dim, name: "lstm", seed: seed)
      |> then(fn {seq, _state} -> seq end)

    pooled =
      Axon.layer(
        fn encoder_out, mask, _opts ->
          masked = Nx.multiply(encoder_out, mask)
          sum = Nx.sum(masked, axes: [1])
          count = Nx.sum(mask, axes: [1]) |> Nx.max(1)
          Nx.divide(sum, count)
        end,
        [encoder, mask_input],
        name: "masked_mean_pool"
      )

    pooled
    |> Axon.dense(128, activation: :relu, name: "dense1")
    |> Axon.dropout(rate: 0.3, name: "dropout", seed: seed)
    |> Axon.dense(1, name: "output")
    |> Axon.sigmoid(name: "score")
  end

  @doc """
  Train the triple scorer on positive and negative triples.

  ## Parameters
    - `positive_triples` - List of `{head, relation, tail}` string tuples
    - `opts` - Training options:
      - `:epochs` - Number of training epochs (default: #{@default_epochs})
      - `:learning_rate` - Learning rate (default: #{@default_learning_rate})
      - `:neg_ratio` - Negative-to-positive ratio (default: 5)
      - `:verbose` - Print per-epoch loss (default: false)
      - `:seed` - Seed for negative sampling, shuffling, parameter
        initialization and the model's random keys (default:
        `Brain.ML.TrainingSeed.get!/0`). Recorded in the config as
        `:training_seed`.
  """
  def train(positive_triples, opts \\ []) do
    epochs = Keyword.get(opts, :epochs, @default_epochs)
    lr = Keyword.get(opts, :learning_rate, @default_learning_rate)
    neg_ratio = Keyword.get(opts, :neg_ratio, 5)
    seed = Keyword.get_lazy(opts, :seed, &TrainingSeed.get!/0)
    rand = TrainingSeed.state(seed)

    entities =
      positive_triples
      |> Enum.flat_map(fn {h, _r, t} -> [h, t] end)
      |> Enum.uniq()

    vocab = build_vocab(positive_triples)
    vocab_size = map_size(vocab)

    model =
      build_model(vocab_size,
        embedding_dim: Keyword.get(opts, :embedding_dim, @default_embedding_dim),
        hidden_dim: Keyword.get(opts, :hidden_dim, @default_hidden_dim),
        seed: seed
      )

    positive_set = MapSet.new(positive_triples)
    {negatives, rand} = generate_negatives(positive_triples, entities, positive_set, neg_ratio, rand)

    all_examples =
      Enum.map(positive_triples, &{&1, 1.0}) ++
        Enum.map(negatives, &{&1, 0.0})

    {shuffled, _rand} = TrainingSeed.shuffle(all_examples, rand)
    {inputs, labels} = encode_examples(shuffled, vocab)

    train_data =
      Stream.repeatedly(fn ->
        {inputs, labels}
      end)

    optimizer = Polaris.Optimizers.adam(learning_rate: lr)
    log_interval = if Keyword.get(opts, :verbose, false), do: 1, else: 0

    params =
      model
      |> Axon.Loop.trainer(:binary_cross_entropy, optimizer, log: log_interval, seed: seed)
      |> Axon.Loop.run(train_data, Axon.ModelState.empty(),
        epochs: epochs,
        iterations: 1,
        compiler: EXLA
      )

    params = transfer_to_binary_backend(params)

    config = %{
      vocab_size: vocab_size,
      embedding_dim: Keyword.get(opts, :embedding_dim, @default_embedding_dim),
      hidden_dim: Keyword.get(opts, :hidden_dim, @default_hidden_dim),
      max_seq_length: @default_max_seq_length,
      training_seed: seed
    }

    {:ok, model, params, vocab, config}
  end

  @doc """
  Save a trained model to disk.

  Accepts optional `relation_coverage` and `model_version` in opts.
  """
  def save_model(params, vocab, config, path, opts \\ []) do
    File.mkdir_p!(Path.dirname(path))

    data =
      %{params: params, vocab: vocab, config: config}
      |> maybe_put(:relation_coverage, Keyword.get(opts, :relation_coverage))
      |> maybe_put(:model_version, Keyword.get(opts, :model_version))

    File.write!(path, Brain.ML.ModelStore.serialize(data))
    :ok
  end

  defp maybe_put(map, _key, nil), do: map
  defp maybe_put(map, key, value), do: Map.put(map, key, value)

  @doc """
  Load a trained model from disk.
  """
  def load_model(path) do
    case File.read(path) do
      {:ok, binary} ->
        data = :erlang.binary_to_term(binary)
        {:ok, %{data | params: ensure_model_state(data.params)}}

      {:error, reason} ->
        {:error, reason}
    end
  end

  # --- Private ---

  defp do_score(head, relation, tail, state) do
    text = "[HEAD] #{head} [REL] #{relation} [TAIL] #{tail}"
    {input, mask} = encode_single(text, state.vocab, @default_max_seq_length)

    output =
      Axon.predict(
        state.model,
        state.params,
        %{
          "input" => input,
          "mask" => mask
        },
        compiler: EXLA
      )

    score = output |> Nx.squeeze() |> Nx.to_number()
    {:ok, score}
  end

  defp build_vocab(triples) do
    all_tokens =
      triples
      |> Enum.flat_map(fn {h, r, t} ->
        tokenize_triple("[HEAD] #{h} [REL] #{r} [TAIL] #{t}")
      end)
      |> Enum.uniq()

    (@special_tokens ++ all_tokens)
    |> Enum.uniq()
    |> Enum.with_index()
    |> Map.new()
  end

  defp encode_examples(examples, vocab) do
    max_len = @default_max_seq_length

    {input_list, label_list} =
      Enum.unzip(
        Enum.map(examples, fn {{h, r, t}, label} ->
          text = "[HEAD] #{h} [REL] #{r} [TAIL] #{t}"
          tokens = tokenize_triple(text)

          indices =
            tokens
            |> Enum.take(max_len)
            |> Enum.map(&Map.get(vocab, &1, 0))

          padded =
            indices ++ List.duplicate(Map.get(vocab, "[PAD]", 0), max_len - length(indices))

          mask =
            List.duplicate(1.0, min(length(indices), max_len)) ++
              List.duplicate(0.0, max_len - min(length(indices), max_len))

          {%{input: padded, mask: Enum.map(mask, &[&1])}, label}
        end)
      )

    inputs = %{
      "input" => Nx.tensor(Enum.map(input_list, & &1.input), type: :s32),
      "mask" => Nx.tensor(Enum.map(input_list, & &1.mask))
    }

    labels = Nx.tensor(Enum.map(label_list, &[&1]))

    {inputs, labels}
  end

  @doc false
  def encode_single_public(text, vocab) do
    encode_single(text, vocab, @default_max_seq_length)
  end

  defp encode_single(text, vocab, max_len) do
    tokens = tokenize_triple(text)

    indices =
      tokens
      |> Enum.take(max_len)
      |> Enum.map(&Map.get(vocab, &1, 0))

    padded = indices ++ List.duplicate(Map.get(vocab, "[PAD]", 0), max_len - length(indices))

    mask =
      List.duplicate(1.0, min(length(indices), max_len)) ++
        List.duplicate(0.0, max_len - min(length(indices), max_len))

    input = Nx.tensor([padded], type: :s32)
    mask_tensor = Nx.tensor([Enum.map(mask, &[&1])])

    {input, mask_tensor}
  end

  defp tokenize_triple(text) do
    split_pattern =
      @special_tokens
      |> Enum.reject(&(&1 == "[PAD]"))
      |> Enum.map(&Regex.escape/1)
      |> Enum.join("|")

    text
    |> String.split(Regex.compile!("(#{split_pattern})"), include_captures: true, trim: true)
    |> Enum.flat_map(fn segment ->
      if segment in @special_tokens do
        [segment]
      else
        Tokenizer.tokenize_normalized(String.trim(segment))
      end
    end)
  end

  # Negative sampling draws from `rand` and returns it advanced, so the same
  # seed always yields the same negatives.
  defp generate_negatives(positives, entities, positive_set, ratio, rand) do
    entity_types = build_entity_type_index(entities)

    Enum.flat_map_reduce(positives, rand, fn {h, r, t}, rand ->
      type_constrained_count = div(ratio * 4, 5)
      uniform_count = ratio - type_constrained_count

      {type_constrained, rand} =
        generate_type_constrained(
          h,
          r,
          t,
          entities,
          entity_types,
          positive_set,
          type_constrained_count,
          rand
        )

      {uniform, rand} =
        sample_corruptions({h, r, t}, entities, entities, positive_set, uniform_count, rand)

      {type_constrained ++ uniform, rand}
    end)
  end

  defp generate_type_constrained(h, r, t, entities, entity_types, positive_set, count, rand) do
    h_peers = type_peers(entity_types, h, entities)
    t_peers = type_peers(entity_types, t, entities)

    sample_corruptions({h, r, t}, h_peers, t_peers, positive_set, count, rand)
  end

  # The members of every type `entity` belongs to; every entity when it has no
  # type in the hierarchy.
  defp type_peers(entity_types, entity, entities) do
    case Map.get(entity_types, entity, []) do
      [] -> entities
      types -> types |> Enum.flat_map(&Map.fetch!(entity_types, {:type_members, &1})) |> Enum.uniq()
    end
  end

  # Replaces the head (from h_peers) or the tail (from t_peers) with even odds,
  # skipping any corruption that is itself a positive, until `count` are drawn.
  defp sample_corruptions(triple, h_peers, t_peers, positive_set, count, rand),
    do: sample_corruptions(triple, h_peers, t_peers, positive_set, count, rand, [])

  defp sample_corruptions(_triple, _hp, _tp, _set, 0, rand, acc), do: {Enum.reverse(acc), rand}

  defp sample_corruptions({h, r, t} = triple, h_peers, t_peers, set, count, rand, acc) do
    {coin, rand} = :rand.uniform_s(rand)

    {corrupted, rand} =
      if coin > 0.5 do
        {head, rand} = TrainingSeed.pick(h_peers, rand)
        {{head, r, t}, rand}
      else
        {tail, rand} = TrainingSeed.pick(t_peers, rand)
        {{h, r, tail}, rand}
      end

    if MapSet.member?(set, corrupted) do
      sample_corruptions(triple, h_peers, t_peers, set, count, rand, acc)
    else
      sample_corruptions(triple, h_peers, t_peers, set, count - 1, rand, [corrupted | acc])
    end
  end

  # entity => its parent types, and {:type_members, type} => the entities under
  # that type. An entity under several types is a member of each.
  defp build_entity_type_index(entities) do
    entity_to_types =
      entities
      |> Map.new(&{&1, Brain.Analysis.TypeHierarchy.parents_of(&1)})
      |> Map.reject(fn {_entity, types} -> types == [] end)

    type_members =
      entity_to_types
      |> Enum.flat_map(fn {entity, types} -> Enum.map(types, &{&1, entity}) end)
      |> Enum.group_by(&elem(&1, 0), &elem(&1, 1))
      |> Map.new(fn {type, members} -> {{:type_members, type}, members} end)

    Map.merge(entity_to_types, type_members)
  end

  defp ensure_model_state(%Axon.ModelState{} = state), do: state
  defp ensure_model_state(params) when is_map(params), do: Axon.ModelState.new(params)

  defp transfer_to_binary_backend(%Axon.ModelState{} = model_state) do
    data =
      model_state.data
      |> Map.new(fn {key, value} -> {key, transfer_value(value)} end)

    %{model_state | data: data}
  end

  defp transfer_to_binary_backend(params) when is_map(params) do
    Map.new(params, fn {key, value} -> {key, transfer_value(value)} end)
  end

  defp transfer_value(%Nx.Tensor{} = tensor) do
    Nx.backend_transfer(tensor, Nx.BinaryBackend)
  end

  defp transfer_value(map) when is_map(map) do
    Map.new(map, fn {k, v} -> {k, transfer_value(v)} end)
  end

  defp transfer_value(other), do: other
end
